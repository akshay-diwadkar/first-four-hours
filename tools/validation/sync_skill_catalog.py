#!/usr/bin/env python3
"""Project the filesystem-owned skill domains into distribution metadata and the docs skill facts table, and check the README, docs skill catalogs, and documented paths against them."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import cast

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "validation"))

import validate_repository as repository_validator  # noqa: E402

REFERENCE_PAGE = ROOT / "docs" / "reference" / "README.md"
HANDOFF_PAGE = "docs/concepts/handoffs.md"
TABLE_BEGIN = "<!-- skill-facts:begin: generated by python tools/validation/sync_skill_catalog.py --write -->"
TABLE_END = "<!-- skill-facts:end -->"
HANDOFF_FOLDER_RE = re.compile(r'ARTIFACT_ROOT,\s*"([a-z][a-z0-9-]*)"\s*\)')
DOCUMENTED_FOLDER_RE = re.compile(r"\.first-four-hours/([a-z][a-z0-9-]*)")
DOCUMENTED_SKILL_RE = re.compile(r"(?<![\w./-])skills/([a-z][a-z0-9-]*)/([a-z][a-z0-9-]*)")


def domain_groups() -> dict[str, list[str]]:
    discovered = repository_validator.discover_skills()
    return {
        domain: [
            f"./skills/{skill.parent.name}/{skill.name}"
            for skill in discovered
            if skill.parent.name == domain
        ]
        for domain in ("workbench", "sensemaking", "learning")
    }


def groups() -> dict[str, list[str]]:
    return {"first-four-hours": [path for paths in domain_groups().values() for path in paths]}


def _projected_marketplace(payload: dict[str, object]) -> dict[str, object]:
    projected = dict(payload)
    raw_plugins = cast(list[object], payload.get("plugins", []))
    existing = {
        str(plugin.get("name")): plugin
        for plugin in raw_plugins
        if isinstance(plugin, dict) and isinstance(plugin.get("name"), str)
    }
    description = "Skills for repository-grounded project work and decision readiness, and for learning any subject."
    plugins: list[dict[str, object]] = []
    for name, paths in groups().items():
        base = dict(existing.get(name, {}))
        base.update({"name": name, "source": "./", "description": description, "skills": paths})
        plugins.append(base)
    projected["name"] = "first-four-hours"
    projected["description"] = description
    projected["plugins"] = plugins
    return projected


def validate(readme: Path, marketplace: Path) -> list[str]:
    errors: list[str] = []
    try:
        payload = json.loads(marketplace.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        return [f"marketplace unreadable: {exc}"]
    if payload != _projected_marketplace(payload):
        errors.append(".claude-plugin/marketplace.json is not derived from the current domain tree")
    try:
        text = readme.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return [f"README unreadable: {exc}"]
    if "### Workbench" not in text or "### Sensemaking" not in text or "### Learning" not in text:
        errors.append("README.md must explain Workbench, Sensemaking, and Learning")
    for path in sum(domain_groups().values(), []):
        link = path.removeprefix("./")
        if f"{link}/SKILL.md" not in text:
            errors.append(f"README.md is missing the active skill link {link}/SKILL.md")
    return errors


def validate_skill_pages(index_text: str, page_stems: set[str], domains: dict[str, list[str]]) -> list[str]:
    errors: list[str] = []
    text = "\n" + index_text.replace("\r\n", "\n")
    for domain, names in domains.items():
        heading = f"\n## {domain}\n"
        start = text.find(heading)
        if start < 0:
            errors.append(f"docs/skills/README.md must have a '## {domain}' section")
        else:
            body_start = start + len(heading)
            end = text.find("\n## ", body_start - 1)
            section = text[body_start:end] if end >= 0 else text[body_start:]
            for name in names:
                if f"]({name}.md)" not in section:
                    errors.append(f"docs/skills/README.md is missing the {domain} skill page link {name}.md")
        for name in names:
            if name not in page_stems:
                errors.append(f"docs/skills/{name}.md is missing for the active skill {name}")
    active = {name for names in domains.values() for name in names}
    for stem in sorted(page_stems - active):
        errors.append(f"docs/skills/{stem}.md documents no active skill")
    return errors


def check() -> list[str]:
    errors = validate(ROOT / "README.md", ROOT / ".claude-plugin" / "marketplace.json")
    pages_dir = ROOT / "docs" / "skills"
    try:
        index_text = (pages_dir / "README.md").read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        return errors + [f"docs/skills/README.md unreadable: {exc}"]
    page_stems = {page.stem for page in pages_dir.glob("*.md") if page.name != "README.md"}
    domains = {
        key.title(): [path.rsplit("/", 1)[1] for path in paths]
        for key, paths in domain_groups().items()
    }
    errors += validate_skill_pages(index_text, page_stems, domains)
    try:
        reference_text = REFERENCE_PAGE.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        errors.append(f"docs/reference/README.md unreadable: {exc}")
    else:
        errors += generated_block_errors(reference_text, skill_facts_table(), "docs/reference/README.md")
    documents = {"README.md": (ROOT / "README.md").read_text(encoding="utf-8")}
    if (ROOT / "START_HERE.md").is_file():
        documents["START_HERE.md"] = (ROOT / "START_HERE.md").read_text(encoding="utf-8")
    for document in sorted((ROOT / "docs").rglob("*.md")):
        documents[document.relative_to(ROOT).as_posix()] = document.read_text(encoding="utf-8")
    skill_paths = {path.removeprefix("./") for paths in domain_groups().values() for path in paths}
    return errors + validate_documented_paths(documents, declared_handoff_folders(), skill_paths, HANDOFF_PAGE)


def skill_facts_table() -> str:
    policy = json.loads((ROOT / "invocation-policy.json").read_text(encoding="utf-8"))["skills"]
    lines = [
        "| Skill | Domain | Source | Starts | Python | Extra packages |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for key, paths in domain_groups().items():
        domain = key.title()
        for path in paths:
            rel = path.removeprefix("./")
            name = rel.rsplit("/", 1)[1]
            manifest = ROOT / rel / "skill-protocol.json"
            python = (
                f"{json.loads(manifest.read_text(encoding='utf-8'))['minimum_python']} or later"
                if manifest.is_file()
                else "none"
            )
            packages = (
                f"[`requirements.txt`](../../{rel}/requirements.txt)"
                if (ROOT / rel / "requirements.txt").is_file()
                else "none"
            )
            mode = policy.get(name, "unknown")
            lines.append(
                f"| [`{name}`](../skills/{name}.md) | {domain} | [`{rel}/`](../../{rel}/SKILL.md) | `{mode}` | {python} | {packages} |"
            )
    return "\n".join(lines) + "\n"


def _block_span(text: str) -> tuple[int, int] | None:
    start = text.find(TABLE_BEGIN + "\n")
    if start < 0 or text.count(TABLE_BEGIN) != 1:
        return None
    body = start + len(TABLE_BEGIN) + 1
    end = text.find(TABLE_END, start)
    if end < body:
        return None
    return body, end


def generated_block_errors(text: str, block: str, label: str) -> list[str]:
    span = _block_span(text)
    if span is None:
        return [f"{label}: must contain one generated skill facts table between {TABLE_BEGIN} and {TABLE_END}"]
    if text[span[0]:span[1]] != block:
        return [f"{label}: skill facts table is stale; run python tools/validation/sync_skill_catalog.py --write"]
    return []


def replace_generated_block(text: str, block: str) -> str:
    span = _block_span(text)
    if span is None:
        return text
    return text[:span[0]] + block + text[span[1]:]


def declared_handoff_folders() -> set[str]:
    folders: set[str] = set()
    for script in sorted(ROOT.glob("skills/*/*/scripts/*.py")):
        folders.update(HANDOFF_FOLDER_RE.findall(script.read_text(encoding="utf-8")))
    return folders


def validate_documented_paths(
    documents: dict[str, str], folders: set[str], skill_paths: set[str], handoff_page: str
) -> list[str]:
    errors: list[str] = []
    for label in sorted(documents):
        text = documents[label]
        for folder in sorted(set(DOCUMENTED_FOLDER_RE.findall(text))):
            if folder not in folders:
                errors.append(f"{label}: names .first-four-hours/{folder}/, which no skill script declares")
        for domain, skill in sorted(set(DOCUMENTED_SKILL_RE.findall(text))):
            if f"skills/{domain}/{skill}" not in skill_paths:
                errors.append(f"{label}: names skills/{domain}/{skill}, which is not an active skill folder")
    for folder in sorted(folders):
        if f".first-four-hours/{folder}/" not in documents.get(handoff_page, ""):
            errors.append(f"{handoff_page}: missing the handoff folder .first-four-hours/{folder}/")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.write and not args.check:
        parser.error("choose --write or --check")
    marketplace = ROOT / ".claude-plugin" / "marketplace.json"
    if args.write:
        payload = json.loads(marketplace.read_text(encoding="utf-8"))
        marketplace.write_text(json.dumps(_projected_marketplace(payload), indent=2) + "\n", encoding="utf-8")
        if REFERENCE_PAGE.is_file():
            text = REFERENCE_PAGE.read_text(encoding="utf-8")
            REFERENCE_PAGE.write_text(replace_generated_block(text, skill_facts_table()), encoding="utf-8", newline="\n")
    errors = check()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    print("skill catalog projection: ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
